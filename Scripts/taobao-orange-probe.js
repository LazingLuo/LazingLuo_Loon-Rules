// Orange observer 2026-10-25.1. Always passes the original request/response.
(function () {
  'use strict';
  const KEY = 'LAZING_TB_ORANGE_PROBE_V1';
  const MAX = 512 * 1024;
  const HOSTS = ['orange-dc.m.taobao.com', 'dorangesource.alicdn.com'];
  const GROUPS = ['ios_bootimage_client', 'bootimage_emergency'];
  const BOOLS = ['isColdStartEnabled', 'isHotStartEnabled', 'useNewCommercialSplash'];
  const NUMBERS = ['backgroundWaitSeconds', 'periodSeconds', 'coldStartFusingTime'];
  const FIELDS = BOOLS.concat(NUMBERS, ['disabledItemCount']);
  const own = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
  const object = o => o !== null && typeof o === 'object' && !Array.isArray(o);
  const count = n => Number.isSafeInteger(n) && n >= 0 ? Math.min(n, 1000000) : 0;
  const stamp = n => n ? new Date(n + 8 * 3600000).toISOString().slice(0, 19).replace('T', ' ') : '尚无';
  function blank() {
    return { version: 1, requests: 0, responses: 0, parsed: 0, hints: 0, settings: 0,
      lastAt: 0, lastStatus: 0, lastResult: '尚无记录', known: {}, notices: {} };
  }
  function scalar(key, value) {
    if (BOOLS.indexOf(key) >= 0) {
      if (value === true || value === false) return value;
      if (value === 'true' || value === 'false') return value === 'true';
      if (value === 0 || value === 1 || value === '0' || value === '1') return Number(value) === 1;
    }
    if ((NUMBERS.indexOf(key) >= 0 || key === 'disabledItemCount') && (typeof value === 'number' ||
      typeof value === 'string' && /^-?\d{1,13}$/.test(value))) {
      const n = Number(value);
      if (Number.isSafeInteger(n) && Math.abs(n) <= 1000000000000) return n;
    }
    return undefined;
  }
  function read() {
    const s = blank();
    try {
      const raw = JSON.parse($persistentStore.read(KEY) || 'null');
      if (!object(raw) || raw.version !== 1) return s;
      ['requests', 'responses', 'parsed', 'hints', 'settings'].forEach(k => { s[k] = count(raw[k]); });
      ['lastAt', 'lastNoticeAt', 'lastSettingsNoticeAt'].forEach(k => {
        if (Number.isSafeInteger(raw[k]) && raw[k] > 0 && raw[k] <= 8640000000000000) s[k] = raw[k];
      });
      // Only fixed strings generated by this script are restored for display.
      if (RESULTS.indexOf(raw.lastResult) >= 0) s.lastResult = raw.lastResult;
      if (Number.isInteger(raw.lastStatus) && raw.lastStatus >= 100 && raw.lastStatus <= 599) s.lastStatus = raw.lastStatus;
      if (HOSTS.indexOf(raw.lastHost) >= 0) s.lastHost = raw.lastHost;
      if (object(raw.known)) GROUPS.forEach(g => {
        if (!object(raw.known[g])) return;
        const values = {};
        FIELDS.forEach(k => { const v = scalar(k, raw.known[g][k]); if (v !== undefined) values[k] = v; });
        if (Object.keys(values).length) s.known[g] = values;
      });
    } catch (_) {}
    return s;
  }
  const RESULTS = ['尚无记录', '看到配置请求', '收到响应，本条没有开屏组名',
    '看到开屏组名，尚无可识别的设置', '找到开屏设置', '本条响应为空',
    '本条是二进制响应', '本条响应超过检查上限', '本条不是可读取的JSON配置',
    '本条JSON结构超过检查上限', '本条接口返回异常状态', '本条响应使用缓存', '检查失败'];
  function save(s) { try { $persistentStore.write(JSON.stringify(s), KEY); } catch (_) {} }
  function notice(title, body) { try { $notification.post('淘宝 Orange', title, body); } catch (_) {} }
  function hostOfRequest(req) {
    const match = /^https?:\/\/(\[[0-9a-f:]+\]|[^\/?#:]+)(?::\d+)?(?:[\/?#]|$)/i.exec(String(req.url || ''));
    if (!match) return null;
    const host = match[1].toLowerCase();
    if (HOSTS.indexOf(host) >= 0) return host;
    if (!/^(?:\d{1,3}\.){3}\d{1,3}$/.test(host) && !/^\[[0-9a-f:]+\]$/i.test(host)) return null;
    const headers = object(req.headers) ? req.headers : {};
    for (const key of Object.keys(headers)) {
      if (key.toLowerCase() !== 'host') continue;
      const logical = String(headers[key]).toLowerCase().replace(/:\d+$/, '');
      if (HOSTS.indexOf(logical) >= 0) return logical;
    }
    return null;
  }
  function parse(text) {
    let doc;
    try { doc = JSON.parse(text); }
    catch (_) {
      const p = /^\s*[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*\s*\(([\s\S]*)\)\s*;?\s*$/.exec(text);
      if (!p) throw new Error('json');
      doc = JSON.parse(p[1]);
    }
    // Some Orange containers encode their JSON once more as a string.
    if (typeof doc === 'string') doc = JSON.parse(doc);
    if (doc === null || typeof doc !== 'object') throw new Error('json');
    return doc;
  }
  function inspect(doc) {
    let visited = 0, decoded = 0;
    const hints = {}, settings = {};
    function walk(v, depth, group) {
      if (++visited > 12000 || depth > 24) throw new Error('limit');
      if (typeof v === 'string') {
        if (GROUPS.indexOf(v) >= 0) hints[v] = true;
        if (v.length <= MAX && /^[\s]*[\[{]/.test(v)) {
          decoded += v.length;
          if (decoded > MAX) throw new Error('limit');
          let inner;
          try { inner = JSON.parse(v); } catch (_) { return; }
          walk(inner, depth + 1, group);
        }
        return;
      }
      if (Array.isArray(v)) { v.forEach(x => walk(x, depth + 1, group)); return; }
      if (!object(v)) return;
      let here = group;
      ['name', 'namespace', 'nameSpace', 'groupName', 'namespaceName'].forEach(k => {
        if (!own(v, k) || typeof v[k] !== 'string') return;
        // A named sibling group must not inherit another group's context.
        if (GROUPS.indexOf(v[k]) >= 0) { here = v[k]; hints[here] = true; }
        else if (k !== 'name' || own(v, 'content') || own(v, 'config') || own(v, 'configs') || own(v, 'value')) here = null;
      });
      if (here) BOOLS.concat(NUMBERS).forEach(k => {
        if (!own(v, k)) return;
        const val = scalar(k, v[k]);
        if (val !== undefined) { if (!settings[here]) settings[here] = {}; settings[here][k] = val; }
      });
      if (here === 'bootimage_emergency' && own(v, 'disableItemId') &&
          typeof v.disableItemId === 'string' && v.disableItemId.length <= 4096) {
        if (!settings[here]) settings[here] = {};
        settings[here].disabledItemCount = v.disableItemId.split(',').filter(x => x.trim().length > 0).length;
      }
      Object.keys(v).forEach(k => {
        const next = GROUPS.indexOf(k) >= 0 ? k : here;
        if (GROUPS.indexOf(k) >= 0) hints[k] = true;
        walk(v[k], depth + 1, next);
      });
    }
    walk(doc, 0, null);
    return { hints: Object.keys(hints), settings: settings };
  }
  function summary(s) {
    const lines = ['请求 ' + s.requests + ' 次；响应 ' + s.responses + ' 次',
      '可读JSON ' + s.parsed + ' 次', '开屏组名 ' + s.hints + ' 次；开屏设置 ' + s.settings + ' 次',
      '最近检查：' + stamp(s.lastAt) + '（北京时间）',
      '最近结果：' + s.lastResult + (s.lastStatus ? '；HTTP ' + s.lastStatus : '')];
    GROUPS.forEach(g => { if (s.known[g]) {
      lines.push(g);
      FIELDS.forEach(k => { if (own(s.known[g], k)) lines.push(k + ' = ' + s.known[g][k]); });
    } });
    return lines.join('\n');
  }
  try {
    if (typeof $request === 'undefined') {
      if (typeof $argument === 'string' && $argument === 'reset') {
        save(blank()); notice('记录已清空', '可以开始新一轮检查');
      } else {
        const text = summary(read()); console.log('[Orange检查] ' + text); notice('检查结果', text);
      }
      return;
    }
    const logicalHost = hostOfRequest($request);
    if (!logicalHost) return;
    const s = read();
    s.lastAt = Date.now(); s.lastHost = logicalHost;
    if (typeof $response === 'undefined') {
      s.requests = count(s.requests + 1); s.lastResult = '看到配置请求'; s.lastStatus = 0;
      save(s); console.log('[Orange检查] 看到配置请求：' + logicalHost); return;
    }
    s.responses = count(s.responses + 1);
    const code = Number($response.status || $response.statusCode);
    s.lastStatus = Number.isInteger(code) && code >= 100 && code <= 599 ? code : 0;
    let found = null;
    const raw = $response.body;
    if (code === 304) s.lastResult = '本条响应使用缓存';
    else if (code < 200 || code >= 300 || !s.lastStatus) s.lastResult = '本条接口返回异常状态';
    else if (raw === undefined || raw === null || raw === '') s.lastResult = '本条响应为空';
    else if (typeof raw !== 'string') s.lastResult = '本条是二进制响应';
    else if (raw.length > MAX) s.lastResult = '本条响应超过检查上限';
    else {
      try {
        const doc = parse(raw); s.parsed = count(s.parsed + 1);
        found = inspect(doc);
        if (found.hints.length) s.hints = count(s.hints + 1);
        if (Object.keys(found.settings).length) {
          s.settings = count(s.settings + 1); s.lastResult = '找到开屏设置';
          GROUPS.forEach(g => { if (found.settings[g]) s.known[g] = found.settings[g]; });
        } else s.lastResult = found.hints.length ? '看到开屏组名，尚无可识别的设置' : '收到响应，本条没有开屏组名';
      } catch (e) { s.lastResult = e.message === 'limit' ? '本条JSON结构超过检查上限' : '本条不是可读取的JSON配置'; }
    }
    console.log('[Orange检查] ' + logicalHost + '；HTTP ' + s.lastStatus + '；' + s.lastResult);
    const enabled = typeof $argument !== 'object' || !$argument || ($argument.notify !== false && $argument.notify !== 'false');
    if (enabled) {
      const now = Date.now(), actual = found && Object.keys(found.settings).length > 0;
      const key = actual ? 'lastSettingsNoticeAt' : 'lastNoticeAt';
      if (!s[key] || now - s[key] >= 3600000) {
        s[key] = now;
        notice(actual ? '找到开屏设置' : '收到配置响应', s.lastResult + '\n' + logicalHost);
      }
    }
    save(s);
  } catch (_) { console.log('[Orange检查] 检查失败，原内容保留'); }
  finally { $done({}); }
})();
