const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const repo = fs.existsSync(path.join(root, 'Scripts/qinglong-bridge.js'));
const read = (remote, local) => fs.readFileSync(path.join(root, repo ? remote : local), 'utf8');
const bridge = read('Scripts/qinglong-bridge.js', 'loon-qinglong-bridge/qinglong-bridge.js');
const retail = read('Scripts/jd-checkin-capture.js', 'loon-jd-checkin/jd-checkin-capture.js');
const jx = read('Scripts/jd-jxzy-checkin-capture.js', 'loon-jxzy-checkin/jd-jxzy-checkin-capture.js');
const finance = read('Scripts/jd-jr-checkin.js', 'loon-jr-checkin/jd-jr-checkin.js');
function financeFunction(name) {
  const start = finance.indexOf('  function ' + name + '(');
  if (start < 0) throw Error('Missing finance capture helper: ' + name);
  const tail = finance.slice(start + 3), next = /\n  (?:async )?function /.exec(tail);
  if (!next) throw Error('Cannot isolate finance helper: ' + name);
  return finance.slice(start, start + 3 + next.index);
}
const financeCapture = `const ACCOUNT='JD_JR_CHECKIN_ACCOUNT_V1';
const day=()=>new Date(Date.now()+8*3600000).toISOString().slice(0,10);
const read=key=>{try{return JSON.parse($persistentStore.read(key)||'null');}catch(_){return null;}};
const save=(key,value)=>{if(!$persistentStore.write(JSON.stringify(value),key))throw Error('本地记录保存失败');};
const tell=message=>$notification.post('京东金融签到','',message);
${['form','cashScope','loginPin','safeCode','body','doublePage','capture'].map(financeFunction).join('\n')}
capture();`;
function moduleSource(name, source) {
  return `function ${name}(context){
const {$request,$response,$argument,$persistentStore,$notification,$script,$httpClient,console}=context;
const $done=()=>{};
${source}\n}\n`;
}
if (!bridge.includes('(async function () {')) throw Error('Bridge entry changed');
const output = '// Generated by Tools/build-qinglong-capture.cjs. Capture only; no network or signing SDK.\n' +
  moduleSource('runLoginCapture', bridge.replace('(async function () {', 'return (async function () {')) +
  moduleSource('runRetailCapture', retail) + moduleSource('runJxCapture', jx) +
  moduleSource('runFinanceCapture', financeCapture) +
  moduleSource('runPlantTaskCapture', fs.readFileSync(path.join(__dirname, 'plant-task-capture.js'), 'utf8')) +
  fs.readFileSync(path.join(__dirname, 'qinglong-capture-router.js'), 'utf8');
const destination = repo ? path.join(root, 'Scripts/qinglong-credential-capture.js') : path.join(__dirname, 'qinglong-credential-capture.js');
fs.writeFileSync(destination, output);
console.log('Built unified credential capture (' + Buffer.byteLength(output) + ' bytes)');
